import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const server = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const client = resolve(server, process.env.SKILLLUDO_CLIENT_PATH ?? '../SkillLudo_Client');
const check = process.argv.includes('--check');
const mirrors = [
  ['src/protocol.ts', 'assets/scripts/protocol/GameProtocol.ts', (text) => text],
  ['src/game/PathData.ts', 'assets/scripts/game/PathData.ts', (text) => text.replace("'../protocol.js'", "'../protocol/GameProtocol'")]
];
for (const [source, destination, transform] of mirrors) {
  const expected = '// Generated by SkillLudo_Server/scripts/sync-client-contract.mjs. Do not edit.\n' + transform(readFileSync(resolve(server, source), 'utf8')).replace(/\r\n/g, '\n');
  const output = resolve(client, destination);
  if (check) {
    if (readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== expected) throw new Error(`Contract drift: ${destination}`);
  } else {
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(output, expected);
  }
  console.log(`${check ? 'Verified' : 'Synced'} ${destination}`);
}
